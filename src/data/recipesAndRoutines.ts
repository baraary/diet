export function getSmartDefaultMealCat(): MealCategory {
  const hour = new Date().getHours();
  if (hour >= 5 && hour < 11) return 'صبحانه';
  if (hour >= 11 && hour < 16) return 'ناهار';
  if (hour >= 16 && hour < 19) return 'میان‌وعده';
  return 'شام';
}

export function getTodayStr(): string {
  const d = new Date();
  return (
    d.getFullYear() +
    '-' +
    String(d.getMonth() + 1).padStart(2, '0') +
    '-' +
    String(d.getDate()).padStart(2, '0')
  );
}

export function addDaysStr(dateStr: string, offset: number): string {
  const parts = dateStr.split('-').map(Number);
  const d = new Date(parts[0], parts[1] - 1, parts[2]);
  d.setDate(d.getDate() + offset);
  return (
    d.getFullYear() +
    '-' +
    String(d.getMonth() + 1).padStart(2, '0') +
    '-' +
    String(d.getDate()).padStart(2, '0')
  );
}

export function formatJalaliFull(dateStr: string): string {
  try {
    const parts = dateStr.split('-').map(Number);
    const d = new Date(parts[0], parts[1] - 1, parts[2]);
    return new Intl.DateTimeFormat('fa-IR', {
      weekday: 'long',
      day: 'numeric',
      month: 'long',
    }).format(d);
  } catch {
    return dateStr;
  }
}

export function formatJalaliShortDay(dateStr: string): { weekday: string; dayNum: string } {
  try {
    const parts = dateStr.split('-').map(Number);
    const d = new Date(parts[0], parts[1] - 1, parts[2]);
    const weekday = new Intl.DateTimeFormat('fa-IR', { weekday: 'short' }).format(d);
    const dayNum = new Intl.DateTimeFormat('fa-IR', { day: 'numeric' }).format(d);
    return { weekday, dayNum };
  } catch {
    return { weekday: '', dayNum: dateStr.slice(-2) };
  }
}

